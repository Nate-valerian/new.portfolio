function setLanguage(lang) {
  localStorage.setItem("td_lang", lang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  const toggleBtn = document.getElementById("lang-toggle");
  if (toggleBtn) {
    toggleBtn.textContent = lang === "en" ? "RU" : "EN";
  }

  document.querySelectorAll(".project-toggle").forEach((btn) => {
    const extra = btn.nextElementSibling;
    if (!extra) return;
    btn.textContent = extra.classList.contains("hidden")
      ? translations[lang].more_info
      : translations[lang].less_info;
  });
}

function initLanguage() {
  const savedLang = localStorage.getItem("td_lang") || "en";
  setLanguage(savedLang);

  const toggleBtn = document.getElementById("lang-toggle");
  if (toggleBtn) {
    toggleBtn.addEventListener("click", () => {
      const current = localStorage.getItem("td_lang") || "en";
      const next = current === "en" ? "ru" : "en";
      setLanguage(next);
    });
  }
}

function initProjectFilter() {
  const tabs = document.querySelectorAll(".ptab");
  const cards = document.querySelectorAll(".pcard");
  if (!tabs.length || !cards.length) return;

  tabs.forEach((tab) => {
    tab.addEventListener("click", () => {
      tabs.forEach((t) => t.classList.remove("active"));
      tab.classList.add("active");

      const filter = tab.getAttribute("data-filter");

      cards.forEach((card) => {
        const category = card.getAttribute("data-category");
        if (filter === "all" || category === filter) {
          card.classList.remove("hidden");
        } else {
          card.classList.add("hidden");
        }
      });
    });
  });
}

function initProjectToggles() {
  const buttons = document.querySelectorAll(".project-toggle");
  if (!buttons.length) return;

  buttons.forEach((btn) => {
    btn.addEventListener("click", () => {
      const extra = btn.nextElementSibling;
      if (!extra) return;

      extra.classList.toggle("hidden");

      const lang = localStorage.getItem("td_lang") || "en";
      btn.textContent = extra.classList.contains("hidden")
        ? translations[lang].more_info
        : translations[lang].less_info;
    });
  });
}

document.addEventListener("DOMContentLoaded", () => {
  initLanguage();
  initProjectFilter();
  initProjectToggles();
});
