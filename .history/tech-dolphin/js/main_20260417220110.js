function getCurrentLang() {
  return localStorage.getItem("td_lang") || "en";
}

function setCurrentLang(lang) {
  localStorage.setItem("td_lang", lang);
}

function applyTranslations(lang) {
  document.documentElement.lang = lang === "ru" ? "ru" : "en";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = translations[lang]?.[key];
    if (typeof value === "string") {
      el.textContent = value;
    }
  });

  document.querySelectorAll(".lang-toggle").forEach((btn) => {
    btn.textContent = lang === "en" ? "RU" : "EN";
  });

  document.querySelectorAll(".more-btn").forEach((btn) => {
    const label = btn.querySelector(".label");
    if (!label) return;
    const target = btn.nextElementSibling;
    const isOpen = target && target.classList.contains("open");
    label.textContent = isOpen
      ? translations[lang].less
      : translations[lang].more;
  });
}

function initLanguage() {
  const lang = getCurrentLang();
  applyTranslations(lang);

  document.querySelectorAll(".lang-toggle").forEach((btn) => {
    btn.addEventListener("click", () => {
      const current = getCurrentLang();
      const next = current === "en" ? "ru" : "en";
      setCurrentLang(next);
      applyTranslations(next);
    });
  });
}

function initNavToggle() {
  document.querySelectorAll(".nav-toggle").forEach((btn) => {
    btn.addEventListener("click", () => {
      const nav = btn.closest(".nav");
      const links = nav ? nav.querySelector(".nav-links") : null;
      if (!links) return;
      links.classList.toggle("open");
    });
  });

  document.querySelectorAll(".nav-links a").forEach((link) => {
    link.addEventListener("click", () => {
      const nav = link.closest(".nav");
      const links = nav ? nav.querySelector(".nav-links") : null;
      if (links && links.classList.contains("open")) {
        links.classList.remove("open");
      }
    });
  });
}

function initProjectFilters() {
  const filterButtons = document.querySelectorAll(".filter-btn");
  const cards = document.querySelectorAll(".project-card[data-filter]");

  if (!filterButtons.length || !cards.length) return;

  filterButtons.forEach((btn) => {
    btn.addEventListener("click", () => {
      filterButtons.forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");

      const selected = btn.dataset.filter;

      cards.forEach((card) => {
        const raw = card.dataset.filter || "";
        const values = raw.split(/\s+/).filter(Boolean);

        if (selected === "all" || values.includes(selected)) {
          card.classList.remove("is-hidden");
        } else {
          card.classList.add("is-hidden");
        }
      });
    });
  });
}

function initMoreButtons() {
  document.querySelectorAll(".more-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const extra = btn.nextElementSibling;
      const label = btn.querySelector(".label");
      if (!extra || !label) return;

      extra.classList.toggle("open");

      const lang = getCurrentLang();
      label.textContent = extra.classList.contains("open")
        ? translations[lang].less
        : translations[lang].more;
    });
  });
}

function initReveal() {
  const items = document.querySelectorAll(".reveal");
  if (!items.length) return;

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("in");
          observer.unobserve(entry.target);
        }
      });
    },
    {
      threshold: 0.14,
      rootMargin: "0px 0px -40px 0px",
    },
  );

  items.forEach((item) => observer.observe(item));
}

function initActiveNav() {
  const page = document.body.dataset.page;

  if (page === "projects") {
    document
      .querySelectorAll('.nav-links a[href="projects.html"]')
      .forEach((a) => {
        a.classList.add("active");
      });
  }
}

document.addEventListener("DOMContentLoaded", () => {
  initLanguage();
  initNavToggle();
  initProjectFilters();
  initMoreButtons();
  initReveal();
  initActiveNav();
});
